def make_sparse_style_override(
    *,
    project_id: str,
    figure_id: str,
    analysis_snapshot_id: str,
    layers: list[dict[str, Any]],
    created_by: str = "reviewer",
    created_at: str | None = None,
) -> dict[str, Any]:
    """Return a sparse style override record, dropping unchanged/empty fields."""

    clean_layers: list[dict[str, Any]] = []
    for layer in layers:
        if not isinstance(layer, dict):
            raise FigureStyleModelError("Style override layer entries must be objects.")
        layer_id = str(layer.get("layer_id") or "").strip()
        if not layer_id:
            raise FigureStyleModelError("Style override layers require layer_id.")
        clean: dict[str, Any] = {"layer_id": layer_id}
        unknown = sorted(set(layer) - (ALLOWED_LAYER_OVERRIDE_FIELDS | {"layer_id"}))
        if unknown:
            raise FigureStyleModelError(f"Unsupported style override fields for layer '{layer_id}': {unknown}")
        for key in sorted(ALLOWED_LAYER_OVERRIDE_FIELDS):
            if key not in layer:
                continue
            value = layer[key]
            if value is None or value == "":
                continue
            clean[key] = value
        if len(clean) > 1:
            clean_layers.append(clean)
    now = created_at or _utc_now()
    override_id = f"{figure_id}:override:{_sha256_json({'layers': clean_layers, 'created_at': now})[:12]}"
    return {
        "override_id": override_id,
        "figure_id": figure_id,
        "project_id": project_id,
        "analysis_snapshot_id": analysis_snapshot_id,
        "status": "active",
        "created_by": created_by,
        "updated_by": created_by,
        "created_at": now,
        "updated_at": now,
        "superseded_by": "",
        "reset_at": "",
        "overrides": clean_layers,
    }


