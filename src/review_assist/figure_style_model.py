def approve_figure_version(
    project_dir: Path,
    figure_id: str,
    version_id: str,
    *,
    actor: str = "local_reviewer",
) -> dict[str, Any]:
    """Approve one exact figure version without mutating review/export state."""

    project_dir = project_dir.resolve()
    ensure_result = ensure_figure_style_model(project_dir)
    artifacts = load_figure_style_artifacts(project_dir)
    figure_recipe_for(artifacts["recipes"], figure_id)
    clean_version_id = str(version_id or "").strip()
    if not clean_version_id:
        raise FigureStyleModelError("Figure version approval requires version_id.")

    versions_artifact = dict(artifacts["versions"])
    existing_versions = [dict(version) for version in _dict_list(versions_artifact.get("versions", []))]
    target = next(
        (
            version
            for version in existing_versions
            if str(version.get("figure_id") or "") == figure_id and str(version.get("version_id") or "") == clean_version_id
        ),
        None,
    )
    if target is None:
        raise FigureStyleModelError(f"Figure version '{clean_version_id}' is not available for figure '{figure_id}'.")
    _validate_approvable_version_output(project_dir, target)

    now = _utc_now()
    next_versions: list[dict[str, Any]] = []
    previous_approved_version_id = ""
    for version in existing_versions:
        current = dict(version)
        same_figure = str(current.get("figure_id") or "") == figure_id
        current_version_id = str(current.get("version_id") or "")
        if same_figure and current_version_id == clean_version_id:
            current["approval_state"] = "approved"
            current["approved_version"] = True
            current["approved_at"] = now
            current["approved_by"] = actor
            current["updated_at"] = now
            current["updated_by"] = actor
        elif same_figure and str(current.get("approval_state") or "") == "approved":
            previous_approved_version_id = current_version_id
            current["approval_state"] = "modified"
            current["approved_version"] = False
            current["approval_superseded_at"] = now
            current["approval_superseded_by_version_id"] = clean_version_id
            current["updated_at"] = now
            current["updated_by"] = actor
        next_versions.append(current)

    versions_artifact["versions"] = next_versions
    versions_artifact["version_count"] = len(next_versions)
    versions_artifact["updated_at"] = now
    versions_artifact["updated_by"] = actor
    validate_figure_versions_artifact(versions_artifact)
    _write_json(project_dir / FIGURE_VERSIONS_PATH, versions_artifact)
    approved = approved_figure_version(versions_artifact, figure_id)
    return {
        "project_id": str(versions_artifact.get("project_id") or ""),
        "figure_id": figure_id,
        "version_id": clean_version_id,
        "approved_version": approved,
        "previous_approved_version_id": previous_approved_version_id,
        "versions_path": str(project_dir / FIGURE_VERSIONS_PATH),
        "model_initialized": bool(ensure_result.get("initialized", False)),
        "analysis_artifacts_mutated": False,
        "figure_images_mutated": False,
        "review_queue_mutated": False,
        "deliverable_figures_mutated": False,
        "export_artifacts_mutated": False,
    }


