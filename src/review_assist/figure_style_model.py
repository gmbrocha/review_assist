def validate_figure_recipes_artifact(data: dict[str, Any]) -> None:
    recipes = _dict_list(data.get("recipes", []))
    if data.get("recipe_count") != len(recipes):
        raise FigureStyleModelError("Figure recipe count does not match recipes.")
    seen: set[str] = set()
    for recipe in recipes:
        recipe_id = _required_string(recipe, "recipe_id", "recipe")
        if recipe_id in seen:
            raise FigureStyleModelError(f"Duplicate figure recipe id: {recipe_id}")
        seen.add(recipe_id)
        _required_string(recipe, "figure_id", recipe_id)
        if not isinstance(recipe.get("layers"), list):
            raise FigureStyleModelError(f"Figure recipe '{recipe_id}' layers must be a list.")


def validate_style_overrides_artifact(data: dict[str, Any]) -> None:
    overrides = _dict_list(data.get("overrides", []))
    if data.get("override_count") != len(overrides):
        raise FigureStyleModelError("Figure style override count does not match overrides.")
    for override in overrides:
        _required_string(override, "override_id", "override")
        _required_string(override, "figure_id", "override")
        status = _override_status(override)
        if status not in STYLE_OVERRIDE_STATUSES:
            raise FigureStyleModelError(f"Style override '{override.get('override_id')}' has unsupported status.")
        for layer in _dict_list(override.get("overrides", [])):
            unknown = sorted(set(layer) - (ALLOWED_LAYER_OVERRIDE_FIELDS | {"layer_id"}))
            if unknown:
                raise FigureStyleModelError(f"Unsupported style override fields: {unknown}")


def validate_figure_versions_artifact(data: dict[str, Any]) -> None:
    versions = _dict_list(data.get("versions", []))
    if data.get("version_count") != len(versions):
        raise FigureStyleModelError("Figure version count does not match versions.")
    seen: set[str] = set()
    for version in versions:
        version_id = _required_string(version, "version_id", "version")
        if version_id in seen:
            raise FigureStyleModelError(f"Duplicate figure version id: {version_id}")
        seen.add(version_id)
        _required_string(version, "figure_id", version_id)
        if int(version.get("version_number") or 0) < 1:
            raise FigureStyleModelError(f"Figure version '{version_id}' requires positive version_number.")
        if str(version.get("approval_state") or "") not in FIGURE_VERSION_APPROVAL_STATES:
            raise FigureStyleModelError(f"Figure version '{version_id}' has unsupported approval_state.")


def validate_render_jobs_artifact(data: dict[str, Any]) -> None:
    jobs = _dict_list(data.get("render_jobs", []))
    if data.get("render_job_count") != len(jobs):
        raise FigureStyleModelError("Figure render job count does not match render_jobs.")
    for job in jobs:
        _required_string(job, "render_job_id", "render_job")
        if str(job.get("status") or "") not in RENDER_JOB_STATUSES:
            raise FigureStyleModelError(f"Render job '{job.get('render_job_id')}' has unsupported status.")


def _recipe_layers(shown_layers: list[dict[str, Any]]) -> list[dict[str, Any]]:
    counters: dict[str, int] = {}
    layers: list[dict[str, Any]] = []
    for index, layer in enumerate(shown_layers):
        layer_type = str(layer.get("layer_type") or "layer")
        source_id = str(layer.get("source_id") or "").strip()
        layer_id = _stable_layer_id(layer_type, source_id, counters)
        render_style = layer.get("render_style") if isinstance(layer.get("render_style"), dict) else {}
        default_style = _default_style_from_render_style(render_style)
        layers.append(
            {
                "layer_id": layer_id,
                "layer_type": layer_type,
                "source_id": source_id,
                "default_z_index": index,
                "default_visible": True,
                "default_display_name": str(layer.get("label") or layer.get("legend_label") or layer_id),
                "default_legend_label": str(layer.get("legend_label") or layer.get("label") or layer_id),
                "default_style": default_style,
                "feature_count": int(layer.get("feature_count") or 0),
                "geometry_type_counts": layer.get("geometry_type_counts") if isinstance(layer.get("geometry_type_counts"), dict) else {},
                "path": str(layer.get("path") or ""),
                "comparison_unit_ids": _string_list(layer.get("comparison_unit_ids", [])),
                "unit_styles": _dict_list(layer.get("unit_styles", [])),
                "editable_presentation_fields": sorted(ALLOWED_LAYER_OVERRIDE_FIELDS),
            }
        )
    return layers


def _validated_sparse_layers(recipe: dict[str, Any], submitted_layers: list[dict[str, Any]]) -> list[dict[str, Any]]:
    recipe_layers = {str(layer.get("layer_id") or ""): layer for layer in _dict_list(recipe.get("layers", []))}
    comparison_feature_layers = _comparison_feature_layers(recipe)
    cleaned: list[dict[str, Any]] = []
    for layer in submitted_layers:
        if not isinstance(layer, dict):
            raise FigureStyleModelError("Style override layer entries must be objects.")
        layer_id = str(layer.get("layer_id") or "").strip()
        recipe_layer = recipe_layers.get(layer_id) or comparison_feature_layers.get(layer_id)
        if recipe_layer is None:
            raise FigureStyleModelError(f"Unknown style override layer id: {layer_id}")
        unknown = sorted(set(layer) - (V1_LAYER_OVERRIDE_FIELDS | {"layer_id"}))
        if unknown:
            raise FigureStyleModelError(f"Unsupported style override fields for layer '{layer_id}': {unknown}")
        cleaned_layer: dict[str, Any] = {"layer_id": layer_id}
        for key in sorted(V1_LAYER_OVERRIDE_FIELDS):
            if key not in layer:
                continue
            value = _normalize_override_value(key, layer[key], recipe_layer)
            if value is None or _equals_default(key, value, recipe_layer):
                continue
            cleaned_layer[key] = value
        if len(cleaned_layer) > 1:
            cleaned.append(cleaned_layer)
    return cleaned


def _comparison_feature_layers(recipe: dict[str, Any]) -> dict[str, dict[str, Any]]:
    layers: dict[str, dict[str, Any]] = {}
    for layer in _dict_list(recipe.get("layers", [])):
        if str(layer.get("layer_id") or "") != COMPARISON_UNITS_LAYER_ID:
            continue
        unit_styles = {
            str(style.get("comparison_unit_id") or "").strip(): style
            for style in _dict_list(layer.get("unit_styles", []))
            if str(style.get("comparison_unit_id") or "").strip()
        }
        unit_ids = _string_list(layer.get("comparison_unit_ids", [])) or list(unit_styles)
        for index, unit_id in enumerate(unit_ids):
            style = unit_styles.get(unit_id, {})
            color = str(style.get("color") or "").strip()
            feature_layer = dict(layer)
            feature_layer["layer_id"] = f"{COMPARISON_FEATURE_LAYER_PREFIX}{unit_id}"
            feature_layer["default_z_index"] = int(layer.get("default_z_index", 0)) + index
            feature_layer["default_display_name"] = str(
                style.get("label")
                or style.get("full_label")
                or _comparison_unit_fallback_label(unit_id, index)
            )
            default_style = dict(layer.get("default_style") if isinstance(layer.get("default_style"), dict) else {})
            if color:
                default_style["fill_color"] = color
                default_style["stroke_color"] = color
            feature_layer["default_style"] = default_style
            layers[str(feature_layer["layer_id"])] = feature_layer
    return layers


def _comparison_unit_fallback_label(unit_id: str, index: int) -> str:
    match = re.search(r"0*(\d+)$", unit_id)
    if match:
        return f"Unit {int(match.group(1))}"
    return f"Unit {index + 1}"


def _normalize_override_value(key: str, value: Any, recipe_layer: dict[str, Any]) -> Any:
    if value is None:
        return None
    if key in {"visible", "label_visible"}:
        return _coerce_bool(value)
    if key == "z_index":
        if str(value).strip() == "":
            return None
        return _bounded_int(value, key, minimum=0, maximum=999)
    if key == "display_name":
        text = str(value).strip()
        if not text:
            return None
        if len(text) > 120:
            raise FigureStyleModelError("display_name must be 120 characters or fewer.")
        return text
    if key in {"fill_color", "stroke_color"}:
        text = str(value).strip()
        if not text:
            return None
        if not HEX_COLOR_RE.match(text):
            raise FigureStyleModelError(f"{key} must be a CSS hex color like #1A2B3C.")
        return text.upper()
    if key == "fill_opacity":
        if str(value).strip() == "":
            return None
        return _bounded_float(value, key, minimum=0.0, maximum=1.0)
    if key == "stroke_width":
        if str(value).strip() == "":
            return None
        return _bounded_float(value, key, minimum=0.0, maximum=10.0)
    if key == "point_size":
        if str(value).strip() == "":
            return None
        return _bounded_float(value, key, minimum=1.0, maximum=80.0)
    if key == "label_field":
        text = str(value).strip()
        if not text:
            return None
        allowed = _allowed_label_fields(recipe_layer)
        if text not in allowed:
            raise FigureStyleModelError(f"label_field '{text}' is not available for layer '{recipe_layer.get('layer_id')}'.")
        return text
    raise FigureStyleModelError(f"Unsupported style override field: {key}")


def _equals_default(key: str, value: Any, recipe_layer: dict[str, Any]) -> bool:
    default_style = recipe_layer.get("default_style") if isinstance(recipe_layer.get("default_style"), dict) else {}
    defaults = {
        "visible": bool(recipe_layer.get("default_visible", True)),
        "z_index": int(recipe_layer.get("default_z_index", 0)),
        "display_name": str(recipe_layer.get("default_display_name") or ""),
        "fill_color": str(default_style.get("fill_color") or "").upper(),
        "fill_opacity": default_style.get("fill_opacity"),
        "stroke_color": str(default_style.get("stroke_color") or "").upper(),
        "stroke_width": default_style.get("stroke_width"),
        "point_size": default_style.get("point_size"),
        "label_visible": False,
        "label_field": "",
    }
    default = defaults.get(key)
    if default in {None, ""}:
        return value in {None, ""}
    if isinstance(default, bool):
        return bool(value) == default
    if isinstance(default, int):
        try:
            return int(value) == default
        except (TypeError, ValueError):
            return False
    if isinstance(default, float):
        try:
            return abs(float(value) - default) < 0.0001
        except (TypeError, ValueError):
            return False
    return str(value).strip().upper() == str(default).strip().upper()


def _allowed_label_fields(recipe_layer: dict[str, Any]) -> set[str]:
    fields: set[str] = set()
    for key in ("allowed_label_fields", "label_fields", "label_field_options"):
        value = recipe_layer.get(key)
        if isinstance(value, list):
            fields.update(str(item).strip() for item in value if str(item).strip())
    return fields


def _bounded_float(value: Any, label: str, *, minimum: float, maximum: float) -> float:
    try:
        number = float(value)
    except (TypeError, ValueError) as exc:
        raise FigureStyleModelError(f"{label} must be numeric.") from exc
    if number < minimum or number > maximum:
        raise FigureStyleModelError(f"{label} must be between {minimum:g} and {maximum:g}.")
    return number


def _bounded_int(value: Any, label: str, *, minimum: int, maximum: int) -> int:
    try:
        number = int(str(value).strip())
    except (TypeError, ValueError) as exc:
        raise FigureStyleModelError(f"{label} must be an integer.") from exc
    if number < minimum or number > maximum:
        raise FigureStyleModelError(f"{label} must be between {minimum} and {maximum}.")
    return number


def _coerce_bool(value: Any) -> bool:
    if isinstance(value, bool):
        return value
    return str(value).strip().lower() in {"1", "true", "yes", "on"}


def _override_status(override: dict[str, Any]) -> str:
    return str(override.get("status") or "active")


def _version_sort_key(version: dict[str, Any]) -> tuple[str, int, str]:
    timestamp = str(
        version.get("approved_at")
        or version.get("updated_at")
        or version.get("completed_at")
        or version.get("created_at")
        or ""
    )
    try:
        number = int(version.get("version_number") or 0)
    except (TypeError, ValueError):
        number = 0
    return timestamp, number, str(version.get("version_id") or "")


def _validate_approvable_version_output(project_dir: Path, version: dict[str, Any]) -> None:
    output = str(version.get("output_artifact_path") or "").strip()
    if not output:
        if bool(version.get("is_stub", False)) and str(version.get("approval_state") or "") == "autogenerated":
            return
        raise FigureStyleModelError(f"Figure version '{version.get('version_id')}' cannot be approved without output_artifact_path.")
    path = Path(output)
    output_path = path if path.is_absolute() else project_dir / path
    if not output_path.exists():
        raise FigureStyleModelError(f"Figure version '{version.get('version_id')}' output artifact is missing: {output}.")


def _stable_layer_id(layer_type: str, source_id: str, counters: dict[str, int]) -> str:
    if layer_type == "comparison_units":
        base = "comparison_units"
    elif layer_type == "source_layer" and source_id:
        base = f"source:{source_id}"
    elif layer_type == "basemap":
        base = "basemap"
    elif layer_type == "basemap_provenance":
        base = "basemap_provenance"
    else:
        base = layer_type or "layer"
    count = counters.get(base, 0)
    counters[base] = count + 1
    if base in {"basemap", "basemap_provenance"}:
        return f"{base}:{count + 1}"
    if count:
        return f"{base}:{count + 1}"
    return base


def _default_style_from_render_style(render_style: dict[str, Any]) -> dict[str, Any]:
    return {
        "fill_color": render_style.get("color"),
        "fill_opacity": render_style.get("polygon_alpha"),
        "stroke_color": render_style.get("color"),
        "stroke_width": render_style.get("line_width"),
        "point_marker": render_style.get("marker"),
        "point_size": render_style.get("marker_size"),
        "opacity": render_style.get("point_alpha") or render_style.get("line_alpha") or render_style.get("polygon_alpha"),
        "style_source": render_style.get("style_source"),
    }


