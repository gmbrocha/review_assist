def _artifact_reference(project_dir: Path, relative_path: Path) -> dict[str, Any]:
    path = project_dir / relative_path
    record: dict[str, Any] = {
        "path": str(relative_path).replace("\\", "/"),
        "exists": path.exists(),
    }
    if not path.exists():
        return record
    stat = path.stat()
    record["size_bytes"] = int(stat.st_size)
    record["modified_at"] = datetime.fromtimestamp(stat.st_mtime, tz=timezone.utc).isoformat()
    if path.is_file() and path.suffix.lower() in {".json", ".geojson"} and stat.st_size <= SMALL_HASH_LIMIT_BYTES:
        record["sha256"] = hashlib.sha256(path.read_bytes()).hexdigest()
    return record


def _project_relative_path(project_dir: Path, value: str | Path) -> str:
    if not str(value or "").strip():
        return ""
    path = Path(value)
    if not path.is_absolute():
        return str(path).replace("\\", "/")
    try:
        return path.resolve().relative_to(project_dir.resolve()).as_posix()
    except ValueError:
        return str(path)


def _required_string(record: dict[str, Any], key: str, label: str) -> str:
    value = record.get(key)
    if not isinstance(value, str) or not value.strip():
        raise FigureStyleModelError(f"{label} requires non-empty {key}.")
    return value


def _dict_list(value: Any) -> list[dict[str, Any]]:
    return [item for item in value if isinstance(item, dict)] if isinstance(value, list) else []


def _string_list(value: Any) -> list[str]:
    return [str(item) for item in value if str(item).strip()] if isinstance(value, list) else []


def _sha256_json(value: Any) -> str:
    payload = json.dumps(value, sort_keys=True, separators=(",", ":"), default=str)
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def _read_json(path: Path) -> dict[str, Any]:
    if not path.exists():
        return {}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise FigureStyleModelError(f"Unable to read figure style artifact {path}: {exc}") from exc
    if not isinstance(data, dict):
        raise FigureStyleModelError(f"Figure style artifact must be a JSON object: {path}")
    return data


def _write_json(path: Path, data: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")


def _utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()
