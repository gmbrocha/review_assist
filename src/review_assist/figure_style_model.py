def initialize_figure_style_model(project_dir: Path) -> dict[str, Any]:
    """Create project-local figure styling metadata from existing generated figures."""

    project_dir = project_dir.resolve()
    try:
        figures_artifact = load_deliverable_figures(project_dir)
    except DeliverableFigureError as exc:
        raise FigureStyleModelError(str(exc)) from exc

    now = _utc_now()
    snapshot = build_analysis_snapshot(project_dir, figures_artifact, created_at=now)
    recipes = [
        build_figure_recipe(
            project_dir,
            figure,
            snapshot["analysis_snapshot_id"],
            project_id=str(figures_artifact.get("project_id") or ""),
        )
        for figure in _all_figures(figures_artifact)
    ]
    versions = [build_autogenerated_version(figure, snapshot["analysis_snapshot_id"], created_at=now) for figure in _all_figures(figures_artifact)]

    recipes_artifact = {
        "schema_version": FIGURE_STYLE_MODEL_VERSION,
        "project_id": str(figures_artifact.get("project_id") or ""),
        "project_name": str(figures_artifact.get("project_name") or ""),
        "created_at": now,
        "analysis_snapshot_id": snapshot["analysis_snapshot_id"],
        "recipe_count": len(recipes),
        "recipes": recipes,
        "output_path": str(project_dir / FIGURE_RECIPES_PATH),
    }
    overrides_artifact = empty_style_overrides_artifact(figures_artifact, created_at=now)
    overrides_artifact["output_path"] = str(project_dir / FIGURE_STYLE_OVERRIDES_PATH)
    versions_artifact = {
        "schema_version": FIGURE_STYLE_MODEL_VERSION,
        "project_id": str(figures_artifact.get("project_id") or ""),
        "project_name": str(figures_artifact.get("project_name") or ""),
        "created_at": now,
        "analysis_snapshot_id": snapshot["analysis_snapshot_id"],
        "version_count": len(versions),
        "versions": versions,
        "output_path": str(project_dir / FIGURE_VERSIONS_PATH),
    }
    render_jobs_artifact = empty_render_jobs_artifact(figures_artifact, created_at=now)
    render_jobs_artifact["output_path"] = str(project_dir / FIGURE_RENDER_JOBS_PATH)

    validate_figure_recipes_artifact(recipes_artifact)
    validate_style_overrides_artifact(overrides_artifact)
    validate_figure_versions_artifact(versions_artifact)
    validate_render_jobs_artifact(render_jobs_artifact)

    _write_json(project_dir / FIGURE_RECIPES_PATH, recipes_artifact)
    _write_json(project_dir / FIGURE_STYLE_OVERRIDES_PATH, overrides_artifact)
    _write_json(project_dir / FIGURE_VERSIONS_PATH, versions_artifact)
    _write_json(project_dir / FIGURE_RENDER_JOBS_PATH, render_jobs_artifact)

    return {
        "project_id": str(figures_artifact.get("project_id") or ""),
        "project_name": str(figures_artifact.get("project_name") or ""),
        "created_at": now,
        "analysis_snapshot": snapshot,
        "recipes_path": str(project_dir / FIGURE_RECIPES_PATH),
        "style_overrides_path": str(project_dir / FIGURE_STYLE_OVERRIDES_PATH),
        "versions_path": str(project_dir / FIGURE_VERSIONS_PATH),
        "render_jobs_path": str(project_dir / FIGURE_RENDER_JOBS_PATH),
        "recipe_count": len(recipes),
        "version_count": len(versions),
        "override_count": 0,
        "render_job_count": 0,
        "mutated_artifact_paths": [
            str(FIGURE_RECIPES_PATH),
            str(FIGURE_STYLE_OVERRIDES_PATH),
            str(FIGURE_VERSIONS_PATH),
            str(FIGURE_RENDER_JOBS_PATH),
        ],
        "analysis_artifacts_mutated": False,
        "figure_images_mutated": False,
        "review_queue_mutated": False,
        "export_artifacts_mutated": False,
    }


def build_analysis_snapshot(project_dir: Path, figures_artifact: dict[str, Any], *, created_at: str | None = None) -> dict[str, Any]:
    project_dir = project_dir.resolve()
    artifact_refs = {
        key: _artifact_reference(project_dir, path)
        for key, path in ANALYSIS_SNAPSHOT_ARTIFACTS.items()
    }
    layer_paths = sorted(
        {
            _project_relative_path(project_dir, path)
            for figure in _all_figures(figures_artifact)
            for path in _figure_layer_paths(figure)
            if str(path or "").strip()
        }
    )
    payload_for_id = {
        "artifacts": artifact_refs,
        "layer_paths": layer_paths,
        "figure_ids": [str(figure.get("figure_id") or "") for figure in _all_figures(figures_artifact)],
    }
    snapshot_id = "analysis-snapshot-" + _sha256_json(payload_for_id)[:16]
    return {
        "analysis_snapshot_id": snapshot_id,
        "schema_version": FIGURE_STYLE_MODEL_VERSION,
        "project_id": str(figures_artifact.get("project_id") or ""),
        "created_at": created_at or _utc_now(),
        "snapshot_basis": "references_existing_review_assist_artifacts",
        "artifacts": artifact_refs,
        "layer_paths": layer_paths,
        "immutable_boundaries": {
            "source_layers_mutated": False,
            "source_status_mutated": False,
            "comparison_geometry_mutated": False,
            "constraints_mutated": False,
            "evidence_mutated": False,
            "tables_mutated": False,
            "report_policy_mutated": False,
        },
    }


