def reset_style_override(overrides_artifact: dict[str, Any], figure_id: str) -> dict[str, Any]:
    """Return a copy of the overrides artifact with active figure overrides marked reset."""

    result = dict(overrides_artifact)
    now = _utc_now()
    overrides: list[dict[str, Any]] = []
    for override in _dict_list(overrides_artifact.get("overrides", [])):
        current = dict(override)
        if str(current.get("figure_id") or "") == figure_id and _override_status(current) == "active":
            current["status"] = "reset"
            current["updated_at"] = now
            current["reset_at"] = now
        overrides.append(current)
    result["overrides"] = overrides
    result["override_count"] = len(result["overrides"])
    result["updated_at"] = now
    validate_style_overrides_artifact(result)
    return result


