def ensure_figure_style_model(project_dir: Path) -> dict[str, Any]:
    """Create missing style model artifacts from current figures, or return existing paths."""

    project_dir = project_dir.resolve()
    paths = [
        project_dir / FIGURE_RECIPES_PATH,
        project_dir / FIGURE_STYLE_OVERRIDES_PATH,
        project_dir / FIGURE_VERSIONS_PATH,
        project_dir / FIGURE_RENDER_JOBS_PATH,
    ]
    if all(path.exists() for path in paths):
        artifacts = load_figure_style_artifacts(project_dir)
        validate_figure_recipes_artifact(artifacts["recipes"])
        validate_style_overrides_artifact(artifacts["style_overrides"])
        validate_figure_versions_artifact(artifacts["versions"])
        validate_render_jobs_artifact(artifacts["render_jobs"])
        return {
            "initialized": False,
            "recipes_path": str(project_dir / FIGURE_RECIPES_PATH),
            "style_overrides_path": str(project_dir / FIGURE_STYLE_OVERRIDES_PATH),
            "versions_path": str(project_dir / FIGURE_VERSIONS_PATH),
            "render_jobs_path": str(project_dir / FIGURE_RENDER_JOBS_PATH),
            "analysis_artifacts_mutated": False,
            "figure_images_mutated": False,
            "review_queue_mutated": False,
            "export_artifacts_mutated": False,
        }
    result = initialize_figure_style_model(project_dir)
    result["initialized"] = True
    return result


def active_style_override(overrides_artifact: dict[str, Any], figure_id: str) -> dict[str, Any] | None:
    matches = [
        override
        for override in _dict_list(overrides_artifact.get("overrides", []))
        if str(override.get("figure_id") or "") == figure_id and _override_status(override) == "active"
    ]
    if not matches:
        return None
    return sorted(matches, key=lambda item: str(item.get("updated_at") or item.get("created_at") or ""))[-1]


def figure_recipe_for(recipes_artifact: dict[str, Any], figure_id: str) -> dict[str, Any]:
    for recipe in _dict_list(recipes_artifact.get("recipes", [])):
        if str(recipe.get("figure_id") or "") == figure_id:
            return recipe
    raise FigureStyleModelError(f"Figure style recipe is not available for figure '{figure_id}'.")


def save_project_style_override(
    project_dir: Path,
    figure_id: str,
    layers: list[dict[str, Any]],
    *,
    actor: str = "local_reviewer",
) -> dict[str, Any]:
    """Validate and persist a sparse active draft style override for one figure."""

    project_dir = project_dir.resolve()
    ensure_result = ensure_figure_style_model(project_dir)
    artifacts = load_figure_style_artifacts(project_dir)
    recipe = figure_recipe_for(artifacts["recipes"], figure_id)
    now = _utc_now()
    clean_layers = _validated_sparse_layers(recipe, layers)
    override_record = make_sparse_style_override(
        project_id=str(recipe.get("project_id") or artifacts["recipes"].get("project_id") or ""),
        figure_id=figure_id,
        analysis_snapshot_id=str(recipe.get("analysis_snapshot_id") or artifacts["recipes"].get("analysis_snapshot_id") or ""),
        layers=clean_layers,
        created_by=actor,
        created_at=now,
    )
    overrides_artifact = dict(artifacts["style_overrides"])
    existing_overrides = [dict(override) for override in _dict_list(overrides_artifact.get("overrides", []))]
    next_overrides: list[dict[str, Any]] = []
    for override in existing_overrides:
        current = dict(override)
        if str(current.get("figure_id") or "") == figure_id and _override_status(current) == "active":
            current["status"] = "superseded"
            current["updated_at"] = now
            current["updated_by"] = actor
            current["superseded_by"] = override_record["override_id"] if override_record["overrides"] else ""
        next_overrides.append(current)
    if override_record["overrides"]:
        next_overrides.append(override_record)
    overrides_artifact["overrides"] = next_overrides
    overrides_artifact["override_count"] = len(next_overrides)
    overrides_artifact["updated_at"] = now
    overrides_artifact["updated_by"] = actor
    validate_style_overrides_artifact(overrides_artifact)
    _write_json(project_dir / FIGURE_STYLE_OVERRIDES_PATH, overrides_artifact)
    return {
        "project_id": str(overrides_artifact.get("project_id") or ""),
        "figure_id": figure_id,
        "style_overrides_path": str(project_dir / FIGURE_STYLE_OVERRIDES_PATH),
        "model_initialized": bool(ensure_result.get("initialized", False)),
        "override_saved": bool(override_record["overrides"]),
        "active_override_id": override_record["override_id"] if override_record["overrides"] else "",
        "active_override": override_record if override_record["overrides"] else None,
        "override_count": len(next_overrides),
        "analysis_artifacts_mutated": False,
        "figure_images_mutated": False,
        "review_queue_mutated": False,
        "export_artifacts_mutated": False,
    }


